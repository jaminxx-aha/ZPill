/// 就地应用 4x5 色彩矩阵到紧凑 RGBA 字节缓冲。
///
/// 契约:[rgba] 为 RGBA 8888 紧凑排列(步长 = 宽 × 4,长度须
/// 为 4 的倍数);[matrix] 20 元素行主序,四行全算(alpha 行
/// 恒单位阵时 alpha 直通);每通道 = M × (r,g,b,a,1) 四舍五入
/// 后钳 0..255。img.Image 管线(image_edit 的 applyEditToImage)
/// 与此同式,一致性由 film_presets_test 交叉对账。
void applyColorMatrix(Uint8List rgba, List<double> matrix) {
  assert(matrix.length == 20, '4x5 矩阵须 20 元素');
  for (var i = 0; i < rgba.length; i += 4) {
    final r = rgba[i], g = rgba[i + 1], b = rgba[i + 2], a = rgba[i + 3];
    rgba[i] = _clamp8(
        matrix[0] * r + matrix[1] * g + matrix[2] * b + matrix[3] * a + matrix[4]);
    rgba[i + 1] = _clamp8(
        matrix[5] * r + matrix[6] * g + matrix[7] * b + matrix[8] * a + matrix[9]);
    rgba[i + 2] = _clamp8(
        matrix[10] * r + matrix[11] * g + matrix[12] * b + matrix[13] * a + matrix[14]);
    rgba[i + 3] = _clamp8(
        matrix[15] * r + matrix[16] * g + matrix[17] * b + matrix[18] * a + matrix[19]);
  }
}

int _clamp8(double v) {
  final r = v.round();
  return r < 0 ? 0 : (r > 255 ? 255 : r);
}
